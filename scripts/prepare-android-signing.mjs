#!/usr/bin/env node
/**
 * Write android/keystore.properties (and optional keystore file) from env vars.
 * Used by CI and local release builds when secrets are not checked into git.
 *
 * Required env:
 *   ANDROID_KEYSTORE_BASE64 — base64-encoded .jks / .keystore file
 *   ANDROID_KEYSTORE_PASSWORD
 *   ANDROID_KEY_ALIAS
 *   ANDROID_KEY_PASSWORD
 *
 * Optional:
 *   ANDROID_KEYSTORE_OUTPUT — path for decoded keystore (default: android/staff-release.keystore)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const androidDir = path.join(root, "android");
const keystorePath =
  process.env.ANDROID_KEYSTORE_OUTPUT ??
  path.join(androidDir, "staff-release.keystore");
const propsPath = path.join(androidDir, "keystore.properties");

const b64 = process.env.ANDROID_KEYSTORE_BASE64?.trim();
const storePassword = process.env.ANDROID_KEYSTORE_PASSWORD;
const keyAlias = process.env.ANDROID_KEY_ALIAS;
const keyPassword = process.env.ANDROID_KEY_PASSWORD;

if (!b64 || !storePassword || !keyAlias || !keyPassword) {
  console.error(
    "prepare-android-signing: set ANDROID_KEYSTORE_BASE64, ANDROID_KEYSTORE_PASSWORD, ANDROID_KEY_ALIAS, ANDROID_KEY_PASSWORD"
  );
  process.exit(1);
}

fs.mkdirSync(androidDir, { recursive: true });
fs.writeFileSync(keystorePath, Buffer.from(b64, "base64"));

const storeFileRelative = path.relative(androidDir, keystorePath).split(path.sep).join("/");
const lines = [
  `# Generated by scripts/prepare-android-signing.mjs — do not commit`,
  `storeFile=${storeFileRelative}`,
  `storePassword=${storePassword}`,
  `keyAlias=${keyAlias}`,
  `keyPassword=${keyPassword}`,
  "",
];

fs.writeFileSync(propsPath, lines.join("\n"), { mode: 0o600 });
console.log("Wrote", propsPath);
console.log("Wrote", keystorePath);
