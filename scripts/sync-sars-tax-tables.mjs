#!/usr/bin/env node
/**
 * Sync SARS tax tables from shared/sars-tax-tables.json into the Deno edge
 * shared module used by fetch-sars-tax-tables.
 *
 *   node scripts/sync-sars-tax-tables.mjs          # write
 *   node scripts/sync-sars-tax-tables.mjs --check  # fail if out of date
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = path.join(root, "shared", "sars-tax-tables.json");
const outPath = path.join(root, "supabase", "functions", "_shared", "sars-tax-tables.ts");
const checkOnly = process.argv.includes("--check");

const raw = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
const years = Object.keys(raw)
  .map(Number)
  .sort((a, b) => a - b);

const yearBlocks = years
  .map((year) => {
    const tables = raw[String(year)];
    return `  ${year}: ${JSON.stringify(tables, null, 2).replace(/\n/g, "\n  ")},`;
  })
  .join("\n");

const generated = `/**
 * AUTO-GENERATED by scripts/sync-sars-tax-tables.mjs — do not edit by hand.
 * Source of truth: shared/sars-tax-tables.json
 * Regenerate: pnpm sync:sars-tax-tables
 */

export type PayeBracketRow = {
  min_income: number;
  max_income: number | null;
  rate: number;
  deduction: number;
};

export type SarsTaxYearTables = {
  startDate: string;
  endDate: string;
  periodLabel: string;
  sourceUrl: string;
  payeBrackets: PayeBracketRow[];
  rebates: {
    under65: number;
    sixtyFiveToSeventyFour: number;
    seventyFivePlus: number;
  };
  uifSdlRates: {
    uif_rate: number;
    uif_cap: number;
    sdl_rate: number;
  };
  medicalTaxCredits: {
    mainMember: number;
    firstDependant: number;
    additionalDependant: number;
  };
};

export const SARS_TAX_TABLES_BY_YEAR: Record<number, SarsTaxYearTables> = {
${yearBlocks}
};

export const SUPPORTED_SARS_TAX_YEARS = Object.keys(SARS_TAX_TABLES_BY_YEAR)
  .map(Number)
  .sort((a, b) => b - a);

export function getSarsTaxTablesForYear(taxYear: number): SarsTaxYearTables | null {
  return SARS_TAX_TABLES_BY_YEAR[taxYear] ?? null;
}

export function buildSarsTaxYearDetails(taxYear: number) {
  const tables = getSarsTaxTablesForYear(taxYear);
  if (!tables) return null;
  return {
    year: taxYear,
    start_date: tables.startDate,
    end_date: tables.endDate,
    description: \`SARS tax year (\${tables.periodLabel})\`,
    rebates: {
      under65: tables.rebates.under65,
      sixtyFiveToSeventyFour: tables.rebates.sixtyFiveToSeventyFour,
      seventyFivePlus: tables.rebates.seventyFivePlus,
    },
  };
}
`;

if (checkOnly) {
  if (!fs.existsSync(outPath)) {
    console.error("sync-sars-tax-tables --check: missing", outPath);
    console.error("Run: pnpm sync:sars-tax-tables");
    process.exit(1);
  }
  const existing = fs.readFileSync(outPath, "utf8");
  if (existing !== generated) {
    console.error("sync-sars-tax-tables --check: Deno copy is out of date.");
    console.error("Run: pnpm sync:sars-tax-tables");
    process.exit(1);
  }
  console.log("sync-sars-tax-tables --check: OK");
  process.exit(0);
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, generated);
console.log("Wrote", path.relative(root, outPath), `(${years.length} tax years)`);
